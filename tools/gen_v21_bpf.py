#!/usr/bin/env python3
"""Receive band-pass for the V.21 low channel (980 / 1180 Hz) of the answering
modem: keeps the echo of our own high channel (1650 / 1850 Hz) and of ANSam
(2100 Hz) out of the carrier detector. Kaiser-windowed sinc, linear phase.
Writes modem/v21_bpf.h. With the argument "bell103": the same for the Bell 103
originate channel (1070 / 1270 Hz) against our 2025 / 2225 Hz, written to
modem/bell103_bpf.h. Pure python."""
import math, sys

FS = 8000.0
N = 81
BELL = "bell103" in sys.argv
LO, HI = (850.0, 1490.0) if BELL else (760.0, 1400.0)      # -6 dB points
MID = 1170.0 if BELL else 1080.0
NAME, GUARD, WHAT, SHOW = (("bell103_bpf", "BELL103_BPF", "Bell 103 originate-channel", (1070, 1270, 2025, 2100, 2225)) if BELL
                           else ("v21_bpf", "V21_BPF", "V.21 low-channel", (980, 1180, 1650, 1850, 2100)))
BETA = 4.5

def i0(x):
    s, t, k = 1.0, 1.0, 1
    while t > 1e-12 * s:
        t *= (x / (2 * k)) ** 2
        s += t
        k += 1
    return s

def taps():
    h = []
    m = (N - 1) / 2.0
    for n in range(N):
        t = n - m
        if t == 0:
            v = 2 * (HI - LO) / FS
        else:
            v = (math.sin(2 * math.pi * HI * t / FS) - math.sin(2 * math.pi * LO * t / FS)) / (math.pi * t)
        w = i0(BETA * math.sqrt(1 - (t / m) ** 2)) / i0(BETA)
        h.append(v * w)
    return h

def gain(h, f):
    re = sum(c * math.cos(2 * math.pi * f * n / FS) for n, c in enumerate(h))
    im = sum(c * math.sin(2 * math.pi * f * n / FS) for n, c in enumerate(h))
    return math.hypot(re, im)

h = taps()
g0 = gain(h, MID)
q = [int(round(c / g0 * 32768)) for c in h]
hq = [c / 32768.0 for c in q]
def db(f): return 20 * math.log10(max(gain(hq, f), 1e-9))
report = {f: db(f) for f in (300, 600, 880, 980, 1070, 1080, 1180, 1270, 1280, 1500, 1650, 1850, 2025, 2100, 2225, 2250, 2550)}
if "--check" in sys.argv:
    for f, v in report.items(): print("%5d Hz %7.2f dB" % (f, v))
    sys.exit(0)
out = ["/* Generated by tools/gen_v21_bpf.py: do not edit.",
       " * %s receive band-pass, %d taps, Q15, linear phase." % (WHAT, N),
       " * Response: " + ", ".join("%d Hz %.1f dB" % (f, v) for f, v in report.items() if f in SHOW) + " */",
       "#ifndef V90D_MODEM_%s_H" % GUARD, "#define V90D_MODEM_%s_H" % GUARD, "#include <stdint.h>",
       "#define %s_N %d" % (GUARD, N), "static const int16_t %s[%s_N] = {" % (NAME, GUARD)]
for i in range(0, N, 9):
    out.append("    " + ", ".join("%6d" % v for v in q[i:i + 9]) + ",")
out += ["};", "#endif", ""]
open("modem/%s.h" % NAME, "w").write("\n".join(out))
