#!/usr/bin/env python3
"""Generate modem/v34_tabs.h: the fractional-delay interpolation filter bank of
the V.34 upstream receiver (8 kHz real samples -> three samples per symbol).

The receiver interpolates linearly between adjacent branches.
Branch p, tap i weights the sample i places behind the newest one and yields
the signal 31 + p/32 samples before the newest sample: a Kaiser-windowed sinc.
Run: python3 tools/gen_v34_tabs.py > modem/v34_tabs.h
"""
import math

P, N, D, BETA = 32, 64, 31, 7.5

def i0(x):
    s, t, k = 1.0, 1.0, 1
    while t > 1e-12 * s:
        t *= (x / (2 * k)) ** 2
        s += t
        k += 1
    return s

def kaiser(u):          # u in [-1, 1]
    return i0(BETA * math.sqrt(1 - u * u)) / i0(BETA) if abs(u) < 1 else 0.0

def sinc(t):
    return 1.0 if abs(t) < 1e-12 else math.sin(math.pi * t) / (math.pi * t)

out = ["/* GENERATED by tools/gen_v34_tabs.py - do not edit. */",
       "#ifndef V90D_MODEM_V34_TABS_H", "#define V90D_MODEM_V34_TABS_H", "#include <stdint.h>", "",
       "#define V34_IP %d      /* fractional-delay branches */" % P,
       "#define V34_IN %d      /* taps per branch */" % N,
       "#define V34_ID %d      /* whole-sample delay of the bank */" % D,
       "/* Q14, unity gain at DC */",
       "static const int16_t v34_interp[V34_IP + 1][V34_IN] = {"]
for p in range(P + 1):      # branch P (one whole sample) closes the interpolation between branches
    h = [sinc(i - D - p / P) * kaiser((i - D - p / P) / (N / 2.0)) for i in range(N)]
    s = sum(h)
    out.append("  {" + ",".join("%d" % round(v / s * 16384) for v in h) + "},")
out.append("};")
out.append("#endif")
print("\n".join(out))
