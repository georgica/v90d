#!/usr/bin/env python3
"""Generate modem/v22_tabs.h: fixed-point filter tables for the V.22bis modem.

  TX: root-raised-cosine (75 % roll-off, V.22bis 2.4) pulse, 40 phases per
      symbol (the 600 baud symbol is 40/3 samples at 8 kHz), 6 symbols long.
  RX: for each channel (1200 / 2400 Hz carrier) a bank of 24 fractional-delay
      complex band-pass matched filters, 67 taps, Hann-windowed RRC shifted to
      the carrier. Branch p evaluates the signal p/24 sample before the newest
      input sample.
Run: python3 tools/gen_v22_tabs.py > modem/v22_tabs.h
"""
import math, cmath

ALPHA = 0.75
SPS = 40.0 / 3.0

def rrc(t, a=ALPHA):
    if abs(t) < 1e-9:
        return 1 - a + 4 * a / math.pi
    if abs(abs(t) - 1 / (4 * a)) < 1e-9:
        return (a / math.sqrt(2)) * ((1 + 2 / math.pi) * math.sin(math.pi / (4 * a))
                                     + (1 - 2 / math.pi) * math.cos(math.pi / (4 * a)))
    return (math.sin(math.pi * t * (1 - a)) + 4 * a * t * math.cos(math.pi * t * (1 + a))) / \
           (math.pi * t * (1 - (4 * a * t) ** 2))

def hann(x):          # x in [-1, 1]
    return 0.5 + 0.5 * math.cos(math.pi * x) if abs(x) < 1 else 0.0

out = []
out.append("/* GENERATED by tools/gen_v22_tabs.py - do not edit. */")
out.append("#ifndef V90D_MODEM_V22_TABS_H\n#define V90D_MODEM_V22_TABS_H\n#include <stdint.h>\n")

# ---- TX pulse: 240 taps at 40 per symbol, peak 1.0 = Q14 ----
TXN = 240
tx = [rrc((i - TXN / 2) / 40.0) * hann((i - TXN / 2) / (TXN / 2.0 + 1)) for i in range(TXN)]
pk = max(tx)
tx = [v / pk for v in tx]
# passband RMS per unit symbol gain for |a|^2 = 10 (see DESIGN notes in v22tx.c)
rms = math.sqrt(10.0 * sum(v * v for v in tx) / 80.0)
out.append("#define V22_TXN 240            /* 6 symbols x 40 phases */")
out.append("#define V22_TX_RMS_Q12 %d    /* line RMS per unit symbol gain, Q12 */" % round(rms * 4096))
out.append("static const int16_t v22_txh[V22_TXN] = {")
for i in range(0, TXN, 12):
    out.append("    " + ", ".join("%6d" % round(v * 16384) for v in tx[i:i + 12]) + ",")
out.append("};\n")

# ---- RX banks ----
P, N = 24, 67
D = (N - 1) / 2.0
out.append("#define V22_RXP %d             /* fractional-delay branches per sample */" % P)
out.append("#define V22_RXN %d             /* taps per branch */" % N)
for name, fc in (("lo", 1200.0), ("hi", 2400.0)):
    out.append("/* [branch][tap][re,im], Q15, gain 2 (output = complex envelope) */")
    out.append("static const int16_t v22_rx_%s[V22_RXP][V22_RXN][2] = {" % name)
    for p in range(P):
        taus = [i - D - p / float(P) for i in range(N)]
        h = [rrc(t / SPS) * hann(t / (D + 1.0)) for t in taus]
        s = sum(h)
        row = []
        for t, v in zip(taus, h):
            c = 2.0 * (v / s) * cmath.exp(2j * math.pi * fc * t / 8000.0)
            row.append("{%d,%d}" % (round(c.real * 32768), round(c.imag * 32768)))
        out.append("  {" + ",".join(row) + "},")
    out.append("};\n")
out.append("#endif")
print("\n".join(out))
