#!/usr/bin/env python3
# Tables for modem/v34mod.c (pure Python, no numpy):
#  - root-raised-cosine pulse, polyphase, for 2400 / 3000 / 3200 symbols/s at 8 kHz
#  - the ten pre-emphasis filters of V.34 Figures 1 and 2 / Tables 3 and 4 as
#    linear-phase FIRs at 8 kHz, per symbol rate (the templates are functions
#    of f / S), and the gain that keeps the transmit power for each carrier.
# Usage: python3 tools/gen_v34mod_tabs.py > modem/v34mod_tabs.h
import math, sys

ALPHA = 0.10        # excess bandwidth: flat over carrier +- 0.45 S (V.34 5.4)
SPAN = 10           # symbols each side
RATES = [(2400, 3, 10), (3000, 3, 8), (3200, 2, 5)]     # S, and S / 8000 = a / b
CARRIERS = {2400: [(2, 3), (3, 4)], 3000: [(3, 5), (2, 3)], 3200: [(4, 7), (3, 5)]}
NPRE = 25           # pre-emphasis FIR taps (odd)

def rrc(t, a):
    if abs(t) < 1e-9:
        return 1 - a + 4 * a / math.pi
    if abs(abs(t) - 1 / (4 * a)) < 1e-9:
        return a / math.sqrt(2) * ((1 + 2 / math.pi) * math.sin(math.pi / (4 * a)) + (1 - 2 / math.pi) * math.cos(math.pi / (4 * a)))
    return (math.sin(math.pi * t * (1 - a)) + 4 * a * t * math.cos(math.pi * t * (1 + a))) / (math.pi * t * (1 - (4 * a * t) ** 2))

def i0(x):
    s = t = 1.0; k = 1
    while t > 1e-12 * s:
        t *= (x / (2 * k)) ** 2; s += t; k += 1
    return s

def pulse(t):
    lim = SPAN + 1.0
    if abs(t) >= lim: return 0.0
    w = i0(1.0 * math.sqrt(1 - (t / lim) ** 2)) / i0(1.0)
    return rrc(t, ALPHA) * w

def template_db(idx, x):
    """pre-emphasis template, dB at normalised frequency x = f / S"""
    if idx == 0: return 0.0
    if idx <= 5:                    # Figure 1 / Table 3: alpha dB at x = 1, straight line from 0
        return 2.0 * idx * x
    beta = 0.5 * (idx - 5); gamma = 1.0 * (idx - 5)     # Figure 2 / Table 4
    if x <= 0.4: return 0.0
    if x <= 0.8: return beta * (x - 0.4) / 0.4
    return beta + gamma * (x - 0.8) / 0.4

def solve(A, b):
    n = len(b)
    M = [A[i][:] + [b[i]] for i in range(n)]
    for c in range(n):
        p = max(range(c, n), key=lambda r: abs(M[r][c]))
        M[c], M[p] = M[p], M[c]
        for r in range(c + 1, n):
            f = M[r][c] / M[c][c]
            for k in range(c, n + 1): M[r][k] -= f * M[c][k]
    x = [0.0] * n
    for c in range(n - 1, -1, -1):
        x[c] = (M[c][n] - sum(M[c][k] * x[k] for k in range(c + 1, n))) / M[c][c]
    return x

def design(S, idx):
    """zero-phase FIR h[-H..H]: amplitude A(w) = c0 + 2 sum c_k cos(k w), least squares"""
    H = NPRE // 2
    fmax = min(1.25 * S, 3950.0)
    fs = [50.0 + i * (fmax - 50.0) / 399 for i in range(400)]
    n = H + 1
    A = [[0.0] * n for _ in range(n)]; b = [0.0] * n
    for f in fs:
        w = 2 * math.pi * f / 8000.0
        row = [1.0] + [2 * math.cos(k * w) for k in range(1, n)]
        d = 10 ** (template_db(idx, f / S) / 20.0)
        for i in range(n):
            b[i] += row[i] * d
            for j in range(n): A[i][j] += row[i] * row[j]
    for i in range(n): A[i][i] += 1e-7
    return solve(A, b)

def amp(c, f):
    w = 2 * math.pi * f / 8000.0
    return c[0] + 2 * sum(c[k] * math.cos(k * w) for k in range(1, len(c)))

out = []
out.append("/* Generated by tools/gen_v34mod_tabs.py: do not edit. */")
out.append("#ifndef V90D_MODEM_V34MOD_TABS_H\n#define V90D_MODEM_V34MOD_TABS_H\n#include <stdint.h>")
out.append("#define V34MOD_SPAN %d\n#define V34MOD_NT %d\n#define V34MOD_NPRE %d" % (SPAN, 2 * SPAN + 1, NPRE))
for S, a, b in RATES:
    tab = [[pulse(ph / b + k - SPAN) for k in range(2 * SPAN + 1)] for ph in range(b)]
    norm = math.sqrt(sum(v * v for r in tab for v in r) / b)
    # ISI of the pulse through its own matched filter, at T / b resolution
    g = [pulse(i / b) for i in range(-b * (SPAN + 1), b * (SPAN + 1) + 1)]
    ac = lambda lag: sum(g[i] * g[i + lag] for i in range(len(g) - lag))
    isi = sum(ac(k * b) ** 2 for k in range(1, 2 * SPAN + 2)) * 2 / ac(0) ** 2
    sys.stderr.write("%d: matched ISI %.1f dB\n" % (S, 10 * math.log10(isi)))
    out.append("static const int16_t v34mod_rrc_%d[%d][V34MOD_NT] = {" % (S, b))
    for r in tab:
        out.append("  { " + ",".join("%d" % round(v / norm * 8192) for v in r) + " },")
    out.append("};")
for S, a, b in RATES:
    out.append("/* pre-emphasis filters 1..10 at %d symbols/s: taps 0..%d of a symmetric FIR, Q13 */" % (S, NPRE // 2))
    out.append("static const int16_t v34mod_pre_%d[10][%d] = {" % (S, NPRE // 2 + 1))
    gains = []
    for idx in range(1, 11):
        c = design(S, idx)
        worst = 0.0
        for (d, e) in CARRIERS[S]:
            dev = [20 * math.log10(amp(c, S * (d / e + x / 100.0))) - template_db(idx, d / e + x / 100.0) for x in range(-45, 46)]
            worst = max(worst, max(abs(v) for v in dev))
        sys.stderr.write("%d filter %d: worst deviation %.2f dB\n" % (S, idx, worst))
        out.append("  { " + ",".join("%d" % round(v * 8192) for v in c) + " },")
        row = []
        for (d, e) in CARRIERS[S]:
            fc = S * d / e
            # power gain over the RRC spectrum of the signal
            num = den = 0.0
            for i in range(-600, 601):
                x = i / 1000.0
                ax = abs(x)
                if ax <= (1 - ALPHA) / 2: p = 1.0
                elif ax >= (1 + ALPHA) / 2: p = 0.0
                else: p = 0.5 * (1 + math.cos(math.pi / ALPHA * (ax - (1 - ALPHA) / 2)))
                num += p * amp(c, fc + x * S) ** 2; den += p
            row.append(round(4096 / math.sqrt(num / den)))
        gains.append(row)
    out.append("};")
    out.append("/* ... and the gain (Q12) that restores the power, [filter - 1][low / high carrier] */")
    out.append("static const int16_t v34mod_pre_gain_%d[10][2] = { " % S + ", ".join("{%d,%d}" % (r[0], r[1]) for r in gains) + " };")
out.append("#endif")
print("\n".join(out))
