#!/usr/bin/env python3
"""Transcribe Tables 8 and 10 of ITU-T V.34 (02/98) from the text conversion
of the Recommendation into test/spec_tables.h. Test oracle only: the library
computes the same numbers from the formulas of clauses 8.2 and 9.2."""
import re, os, sys
here = os.path.dirname(os.path.abspath(__file__))
root = os.path.dirname(here)
src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(root, "..", "refs", "itu", "T-REC-V.34-199802-I.txt")
lines = open(src, encoding="utf-8").read().split("\n")

srates = [2400, 2743, 2800, 3000, 3200, 3429]
# ---- Table 8
t8 = []
i0 = next(i for i, l in enumerate(lines) if "Table 8/V.34" in l and "Switching Pattern" in l)
for l in lines[i0:i0 + 45]:
    m = re.match(r"^\s*(\d{1,2}) (\d00)((?:\s+(?:\d+\s+[0-9A-F]+|\u2013\s+\u2013))+)\s*$", l)
    if not m:
        continue
    rate = int(m.group(1) + m.group(2))
    toks = m.group(3).split()
    assert len(toks) == 12, l
    for k in range(6):
        if toks[2 * k] != "\u2013":
            t8.append((srates[k], rate, int(toks[2 * k]), int(toks[2 * k + 1], 16)))
assert len(t8) == 130, len(t8)

# ---- Table 10
t10 = []
i0 = next(i for i, l in enumerate(lines) if "Table 10/V.34" in l and "Mapping parameters" in l)
i1 = next(i for i, l in enumerate(lines) if l.startswith("9.3 ") and "Parser" in l and i > i0)
grp, prev = 0, 0
L = r"(\d \d{3}|\d{1,3})"
rx = re.compile(r"^\s*(?:(2400|2743|2800|3000|3200|3429)\s+)?(\d{1,2}) (\d00)\s+(\d+)\s+(\d+)\s+(\d+)\s+" + L + r"\s+" + L + r"\s*$")
for l in lines[i0:i1]:
    m = rx.match(l)
    if not m:
        continue
    rate = int(m.group(2) + m.group(3))
    if rate < prev:
        grp += 1
    prev = rate
    if m.group(1):
        assert int(m.group(1)) == srates[grp], l
    t10.append((srates[grp], rate, int(m.group(4)), int(m.group(5)), int(m.group(6)),
                int(m.group(7).replace(" ", "")), int(m.group(8).replace(" ", ""))))
assert len(t10) == 130, len(t10)
assert sorted((a, b) for a, b, *_ in t10) == sorted((a, b) for a, b, *_ in t8)

with open(os.path.join(root, "test", "spec_tables.h"), "w") as f:
    f.write("/* GENERATED by tools/gen_spec_tables.py from the text of ITU-T V.34 (02/98).\n"
            " * Test oracle only. */\n"
            "static const struct { unsigned short S, R; unsigned char b; unsigned short swp; } spec_t8[] = {\n")
    for r in t8:
        f.write("    { %d, %5d, %2d, 0x%04X },\n" % r)
    f.write("};\n\nstatic const struct { unsigned short S, R; unsigned char K, Mmin, Mexp; unsigned short Lmin, Lexp; } spec_t10[] = {\n")
    for r in t10:
        f.write("    { %d, %5d, %2d, %2d, %2d, %4d, %4d },\n" % r)
    f.write("};\n")
print("table 8 rows:", len(t8), "table 10 rows:", len(t10))
