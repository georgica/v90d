#!/usr/bin/env python3
"""Generate v34_constel.c (library table) and test/fig5_data.h (test oracle).

Two independent derivations of ITU-T V.34 Figure 5 are kept apart on purpose:

  * v34_constel.c is computed from the RULE in clause 9.1: the quarter
    superconstellation is the 416 lowest-energy points of the grid 4Z^2+(1,1),
    numbered by increasing magnitude, ties broken by the greatest imaginary
    component first.
  * test/fig5_data.h is the FIGURE itself, as read out of the PDF text layer
    (tools/fig5_from_pdf.json, produced once with `pdftotext -bbox` on page 20
    of T-REC-V.34-199802-I.pdf by snapping every label to its row/column
    heading).

test_constel.c checks that the two agree for all 416 labels.
"""
import json, os, sys
here = os.path.dirname(os.path.abspath(__file__))
root = os.path.dirname(here)

cand = [(x, y) for x in range(-43, 46, 4) for y in range(-43, 46, 4)]
cand.sort(key=lambda p: (p[0] ** 2 + p[1] ** 2, -p[1]))
pts = cand[:416]

with open(os.path.join(root, "v34_constel.c"), "w") as f:
    f.write("/* GENERATED by tools/gen_tables.py from the rule in V.34 clause 9.1.\n"
            " * Do not edit. Quarter superconstellation of Figure 5/V.34:\n"
            " * v34_constel[label] = {re, im}, label 0..415. */\n"
            "#include \"v34_priv.h\"\n\n"
            "const int8_t v34_constel[V34_QPOINTS][2] = {\n")
    for i in range(0, 416, 8):
        f.write("    " + " ".join("{%3d,%3d}," % p for p in pts[i:i + 8]) + "\n")
    f.write("};\n\n"
            "/* Inverse: v34_label[iy][ix], ix = (re+43)/4, iy = (im+43)/4;\n"
            " * 0xFFFF where the grid position is not one of the 416 points. */\n"
            "const uint16_t v34_label[23][23] = {\n")
    lab = {p: i for i, p in enumerate(pts)}
    for iy in range(23):
        row = [lab.get((-43 + 4 * ix, -43 + 4 * iy), 0xFFFF) for ix in range(23)]
        f.write("    {" + ",".join("%5d" % v for v in row) + "},\n")
    f.write("};\n")

fig = json.load(open(os.path.join(here, "fig5_from_pdf.json")))
with open(os.path.join(root, "test", "fig5_data.h"), "w") as f:
    f.write("/* GENERATED by tools/gen_tables.py from the text layer of Figure 5/V.34\n"
            " * (PDF page 20). Test oracle only: fig5[label] = {re, im}. */\n"
            "static const signed char fig5[416][2] = {\n")
    for i in range(0, 416, 8):
        f.write("    " + " ".join("{%3d,%3d}," % tuple(p) for p in fig[i:i + 8]) + "\n")
    f.write("};\n")
print("ok")
